class SpecError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise SpecError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical_json(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True,
                       separators=(",", ":"), allow_nan=False) + "\n").encode("utf-8")


def strict_json(data):
    def pairs(values):
        result = {}
        for k, v in values:
            require(k not in result, "duplicate JSON key: " + k)
            result[k] = v
        return result
    def bad_number(value):
        raise SpecError("non-finite JSON number: " + value)
    return json.loads(data.decode("utf-8"), object_pairs_hook=pairs, parse_constant=bad_number)


def primary_key(r):
    return (0 if r["source_dataset"].endswith("_COMP") else 1, r["original_id"])


def bucket(r):
    return f"{r['macro_subfield']}__{r['provisional_mechanism']}"


def protected_mask(s):
    """Protect complete matching environments, non-CJK brackets, invisible dots.

    A mismatched/unclosed delimiter does not protect its unmatched outer span.
    This is a bounded textual heuristic, not a LaTeX or mathematical parser.
    """
    mask = [False] * len(s)
    def mark(a, b):
        mask[a:b] = [True] * (b - a)
    for m in re.finditer(r"\\(?:left|right)\.", s):
        mark(m.start(), m.end())
    env_stack = []
    for m in re.finditer(r"\\(begin|end)\{([^{}]+)\}", s):
        if m.group(1) == "begin":
            env_stack.append((m.group(2), m.start()))
        elif env_stack and env_stack[-1][0] == m.group(2):
            _, start = env_stack.pop()
            mark(start, m.end())
        else:
            env_stack.clear()
    stack = []
    close = {")": "(", "]": "[", "}": "{", "）": "（"}
    for i, ch in enumerate(s):
        if ch in "([{（":
            stack.append((ch, i))
        elif ch in close:
            if stack and stack[-1][0] == close[ch]:
                _, start = stack.pop()
                if not CJK.search(s[start:i + 1]):
                    mark(start, i + 1)
            else:
                stack.clear()
    return mask


def normalize_for_structure(question):
    require(SUBQ_TOKEN not in question, "reserved marker in input")
    s = question.replace("$", " ")
    s = re.sub(SUBQ_PAT, " " + SUBQ_TOKEN + " ", s)
    mask = protected_mask(s)
    out, i = [], 0
    while i < len(s):
        if not mask[i]:
            out.append(s[i])
            i += 1
        else:
            while i < len(s) and mask[i]:
                i += 1
            out.append(" MATH ")
    return "".join(out)


def _split_text(question, sentence_only=False):
    s = question.replace("$", " ")
    mask = protected_mask(s)
    parts, start = [], 0
    for i, ch in enumerate(s):
        if mask[i]:
            continue
        split = ch in ("。；;！!？?\n" if sentence_only else "，。；;！!？?\n")
        if ch == ".":
            prev = s[i - 1] if i else ""
            nxt = s[i + 1] if i + 1 < len(s) else ""
            # Decimal point between digits, or a leading .5-style decimal.
            decimal = nxt in "0123456789" and bool(nxt) and (
                (prev in "0123456789" and bool(prev)) or not prev or prev in WS + "([{=<>+-*/,:;")
            split = not decimal
        elif ch == "," and not sentence_only:
            prev = s[:i].rstrip(WS)[-1:]
            nxt = s[i + 1:].lstrip(WS)[:1]
            split = bool(CJK.search(prev) or CJK.search(nxt))
        if split:
            parts.append(s[start:i])
            start = i + 1
    parts.append(s[start:])
    return [re.sub("[" + re.escape(WS) + "]+", " ", p).strip(WS) for p in parts]


def split_clauses_raw(question):
    return [p for p in _split_text(question) if len(p) >= 3 and
            not re.fullmatch(r"(?:\([1-9ⅠⅡⅢⅣⅤⅥⅦⅧⅨ]\)|（[1-9一二三四五六七八九ⅠⅡⅢⅣⅤⅥⅦⅧⅨ]）)", p)]


def target_info(question):
    clauses = split_clauses_raw(question)
    if not clauses:
        return clauses, [], []
    indices = [i for i, c in enumerate(clauses) if re.search(ASK_PAT, c)]
    if not indices:
        target_indices = [len(clauses) - 1]
    else:
        last = indices[-1]
        if last > 0 and last >= len(clauses) - 2 and not re.search(r"[:：]\s*$", clauses[last]):
            target_indices = list(range(last, len(clauses)))
        else:
            target_indices = [last]
    stems = [i for i in range(len(clauses)) if i not in target_indices]
    return clauses, stems, target_indices


def split_stem_and_target(question):
    clauses, stems, targets = target_info(question)
    return "。".join(clauses[i] for i in stems), "，".join(clauses[i] for i in targets)


def classify_provisional_mechanism(question):
    clauses, stems, targets = target_info(question)
    target = "，".join(clauses[i] for i in targets)
    if re.search(EXTREMUM_PAT, target):
        return TYPE_B
    # Narrow coreference: "其最小值为 t。求 t 的值"; do not use every prior extremum.
    m = re.search(r"(?:试求|求)\s*([A-Za-z])\s*的值", target)
    if m:
        name = re.escape(m.group(1))
        pat = r"(?:最大值|最小值)\s*(?:记为|记作|为|是)\s*" + name + r"(?![A-Za-z0-9_])"
        if any(re.search(pat, clauses[i]) for i in stems if i < min(targets)):
            return TYPE_B
    return TYPE_A


def math_tokens(text):
    """Keep punctuation, font macros, braces, digits and token boundaries.

    Delimiter sizing commands and $ are formatting-only for this representation.
    Returning tuples prevents x=1.2 / x=12 and (1,23) / (12,3) collisions.
    """
    s = text.replace("$", " ")
    s = re.sub(r"\\(?:left|right)(?![A-Za-z])\.?", "", s)
    token_pat = r"\\[A-Za-z]+|\\[^A-Za-z]|[0-9]+(?:\.[0-9]+)?|\.[0-9]+|[A-Za-z]+|[^" + re.escape(WS) + r"]"
    return tuple(re.findall(token_pat, s))


def first_sentence_key(question):
    first = next((p for p in _split_text(question, sentence_only=True) if p), "")
    return math_tokens(first)


def stem_trigrams(question):
    stem, _ = split_stem_and_target(question)
    tokens = math_tokens(stem)
    return {tokens[i:i + 3] for i in range(len(tokens) - 2)} if len(tokens) >= 20 else set()


def multi_subquestion(question):
    parts = normalize_for_structure(question).split(SUBQ_TOKEN)
    return len(parts) >= 3 and sum(bool(re.search(r"(?:求|试求|计算|确定|写出|证明|求证)", p)) for p in parts[1:]) >= 2


def scalar_answer_has_multiple_values(answer):
    s = answer.strip(WS + "$")
    s = re.sub(r"[，,；;。.\s$]+$", "", s)
    s = re.sub(r"\\(?:left|right)(?![A-Za-z])\.?", "", s).strip(WS)
    # Strip complete outer round groups, not function argument groups.
    while s.startswith("(") and s.endswith(")"):
        depth, closes_at_end = 0, True
        for i, ch in enumerate(s):
            depth += (ch == "(") - (ch == ")")
            if depth == 0 and i < len(s) - 1:
                closes_at_end = False
                break
        if not closes_at_end or depth != 0:
            break
        s = s[1:-1].strip(WS)
    if re.search(r"或|\\pm(?![A-Za-z])|±", s):
        return True
    stack = []
    close = {")": "(", "]": "[", "}": "{", "）": "（"}
    for ch in s:
        if ch in "([{（":
            stack.append(ch)
        elif ch in close and stack and stack[-1] == close[ch]:
            stack.pop()
        elif ch in ",，;；" and not stack:
            return True
    return False


def load_sources(comp_path, cee_path):
    import pyarrow.parquet as pq
    result = []
    for src, path in (("COMP", comp_path), ("CEE", cee_path)):
        content = Path(path).read_bytes()
        expected_rows, expected_hash = SOURCES[src]
        require(sha(content) == expected_hash, "InputHashMismatchError: " + src)
        rows = pq.read_table(io.BytesIO(content)).to_pylist()
        require(len(rows) == expected_rows, "source row count")
        seen = set()
        for r in rows:
            require(type(r["id"]) is int and r["id"] >= 0 and r["id"] not in seen, "invalid source id")
            seen.add(r["id"])
            for name in ("question", "subfield", "answer_type"):
                require(type(r[name]) is str, "source string type: " + name)
            require(bool(r["question"].strip()), "empty question")
            for name in ("solution", "final_answer"):
                require(type(r[name]) is list and all(type(x) is str for x in r[name]), "source list type: " + name)
            require(r["is_multiple_answer"] is None or type(r["is_multiple_answer"]) is bool, "source flag type")
            for name in ("unit", "error"):
                require(r[name] is None or type(r[name]) is str, "source nullable string: " + name)
            for name, expected in (("subject", "Math"), ("language", "Chinese"), ("modality", "Text-only"), ("question_type", "Open-ended")):
                require(r[name] == expected, "unexpected source metadata: " + name)
            require(r["subfield"] in SUBFIELD_MAP, "UnknownSubfieldError")
            require(r["context"] is None, "unexpected nonempty context in pinned data")
            require(all(r[f"image_{i}"] is None for i in range(1, 10)), "unexpected image in pinned source")
            r = dict(r)
            r.update(item_id=f"ob-{src.lower()}-{r['id']}", source_dataset=f"OE_TO_maths_zh_{src}", original_id=r["id"])
            result.append(r)
    return sorted(result, key=primary_key)


def load_audit(path, sources):
    raw = Path(path).read_bytes()
    require(sha(raw) == AUDIT_SHA256, "InputHashMismatchError: audit")
    audit = strict_json(raw)
    require(set(audit) == {"schema_version", "review_method", "flag_corrections", "exclusions"}, "audit top-level fields")
    require(audit["schema_version"] == "audit_overrides_v2.3", "audit schema")
    lookup = {r["item_id"]: r for r in sources}
    require(type(audit["review_method"]) is str, "audit review method")
    require(type(audit["flag_corrections"]) is dict and type(audit["exclusions"]) is dict, "audit dictionaries")
    require(not (set(audit["flag_corrections"]) & set(audit["exclusions"])), "audit overlapping entries")
    for kind in ("flag_corrections", "exclusions"):
        for id_, entry in audit[kind].items():
            require(id_ in lookup, "unknown audit id")
            require(type(entry["evidence"]) is str and len(entry["evidence"].strip()) >= 15, "audit evidence")
            require(entry["source_question_sha256"] == sha(lookup[id_]["question"].encode("utf-8")), "audit question binding")
            if kind == "exclusions":
                require(set(entry) == {"reason_code", "source_question_sha256", "evidence"}, "exclusion fields")
                require(entry["reason_code"] in REASONS[9:13], "audit reason")
            else:
                require(set(entry) == {"source_question_sha256", "expected_source_is_multiple_answer", "override_is_multiple_answer", "evidence"}, "correction fields")
                require(type(entry["override_is_multiple_answer"]) is bool, "correction value")
                require(entry["expected_source_is_multiple_answer"] is lookup[id_]["is_multiple_answer"], "correction source flag")
    return audit


def load_retained(path, sources):
    if path is None:
        return set(), None
    raw = Path(path).read_bytes()
    require(not raw.startswith(b"\xef\xbb\xbf"), "retained BOM")
    lines = raw.splitlines()
    require(len(lines) == 100 and all(line.strip() for line in lines), "retained requires 100 nonblank records")
    lookup = {r["item_id"]: r for r in sources}
    ids = []
    for line in lines:
        r = strict_json(line)
        require(type(r) is dict and type(r.get("id")) is str and r["id"] in lookup, "retained id")
        for field in ("question", "question_sha256"):
            if field in r:
                expected = lookup[r["id"]]["question"] if field == "question" else sha(lookup[r["id"]]["question"].encode("utf-8"))
                require(r[field] == expected, "retained source mismatch")
        ids.append(r["id"])
    require(len(set(ids)) == 100, "retained duplicate ids")
    sorted_ids = [r["item_id"] for r in sources if r["item_id"] in set(ids)]
    return set(ids), {"raw_sha256": sha(raw), "id_set_sha256": sha(canonical_json(sorted_ids)), "count": 100}


def exclusion_reason(source, effective_flag, audit, estimated_count):
    q, ans, solutions = source["question"], source["final_answer"], source["solution"]
    if len(ans) != 1 or not ans[0].strip():
        return REASONS[0]
    if not any(s.strip() for s in solutions):
        return REASONS[1]
    if effective_flag is not False or source["answer_type"] not in {"Numerical", "Expression", "Interval", "Equation", "Tuple"}:
        return REASONS[2]
    if source["answer_type"] in {"Numerical", "Expression", "Equation"} and scalar_answer_has_multiple_values(ans[0]):
        return REASONS[3]
    norm = normalize_for_structure(q)
    if re.search(IMAGE_PAT + "|" + TABLE_PAT, q, flags=re.IGNORECASE) or re.search(VISUAL_WORDS, norm):
        return REASONS[4]
    if re.search(PROOF_PAT, norm):
        return REASONS[5]
    if multi_subquestion(q):
        return REASONS[6]
    for sentence in re.split(r"[。；！\n]", q.replace("$", "")):
        if len(sentence) > 25 and not re.search(r"[0-9a-zA-Z=<>+\-\\]", sentence) and not re.search(MATH_KEYWORDS, sentence):
            return REASONS[7]
    solution_text = "\n".join(solutions)
    for fn in sorted(set(re.findall(FUNCTION_DEF, q))):
        pat = r"(?<![a-zA-Z\\])" + re.escape(fn) + r"(?![a-zA-Z])"
        if len(re.findall(pat, q)) == 1 and not re.search(pat, solution_text):
            return REASONS[8]
    if source["item_id"] in audit["exclusions"]:
        return audit["exclusions"][source["item_id"]]["reason_code"]
    if estimated_count < 3:
        return REASONS[13]
    if estimated_count > 9:
        return REASONS[14]
    return ""


def csv_value(value):
    if value is None:
        return ""
    if type(value) is bool:
        return "true" if value else "false"
    return str(value)


def build(sources, audit, retained_ids=None, retained_metadata=None, test_seed=2026, dev_seed=2027):
    require(type(test_seed) is int and type(dev_seed) is int and 0 <= test_seed < 2**63 and 0 <= dev_seed < 2**63, "seed range")
    sources = sorted(sources, key=primary_key)
    retained_ids = set() if retained_ids is None else set(retained_ids)
    prefer = retained_metadata is not None
    require(prefer == bool(retained_ids), "retained mode consistency")
    require(not prefer or len(retained_ids) == 100, "retained size")
    lookup = {r["item_id"]: r for r in sources}
    records, applied = [], []
    effective = {}
    for s in sources:
        id_ = s["item_id"]
        eff = s["is_multiple_answer"]
        correction = audit["flag_corrections"].get(id_)
        if correction:
            eff = correction["override_is_multiple_answer"]
            applied.append({"item_id": id_, "source_flag": s["is_multiple_answer"], "effective_flag": eff,
                            "question_sha256": sha(s["question"].encode("utf-8"))})
        effective[id_] = eff
        count = len(split_clauses_raw(s["question"]))
        why = exclusion_reason(s, eff, audit, count)
        records.append({
            "item_id": id_, "source_dataset": s["source_dataset"], "original_id": s["original_id"],
            "subfield": s["subfield"], "macro_subfield": SUBFIELD_MAP[s["subfield"]],
            "provisional_mechanism": classify_provisional_mechanism(s["question"]),
            "estimated_clause_count": count, "is_retained_v1": id_ in retained_ids,
            "status_code": "EXCLUDED" if why else "ELIGIBLE_RESERVE",
            "exclusion_stage": "STAGE_" + why[6] if why else "", "exclusion_reason": why,
            "stem_cluster_id": "", "cluster_representative_id": "", "reserve_rank": None,
            "question_sha256": sha(s["question"].encode("utf-8")),
        })
    eligible = [r for r in records if r["status_code"] != "EXCLUDED"]
    fs = [first_sentence_key(lookup[r["item_id"]]["question"]) for r in eligible]
    grams = [stem_trigrams(lookup[r["item_id"]]["question"]) for r in eligible]
    parent = list(range(len(eligible)))
    def root(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for i in range(len(eligible)):
        for j in range(i + 1, len(eligible)):
            prefix_match = len(fs[i]) >= 18 and fs[i] == fs[j]
            overlap = bool(grams[i] and grams[j]) and 100 * len(grams[i] & grams[j]) >= 65 * len(grams[i] | grams[j])
            if prefix_match or overlap:
                a, b = root(i), root(j)
                if a != b:
                    parent[max(a, b)] = min(a, b)
    components = collections.defaultdict(list)
    for i, r in enumerate(eligible):
        components[root(i)].append(r)
    representatives = []
    for key in sorted(components):
        members = components[key]
        canonical_members = sorted(members, key=primary_key)
        cluster_id = "CL_" + sha(canonical_json([r["item_id"] for r in canonical_members]))
        representative = min(members, key=lambda r: (0 if prefer and r["is_retained_v1"] else 1, *primary_key(r)))
        for r in members:
            r["stem_cluster_id"] = cluster_id
            r["cluster_representative_id"] = representative["item_id"]
            if r is not representative:
                r.update(status_code="EXCLUDED", exclusion_stage="STAGE_4", exclusion_reason=REASONS[-1])
        representatives.append(representative)
    pools = {name: [] for name in BUCKETS}
    for r in representatives:
        pools[bucket(r)].append(r)
    deficits = {name: {"available": len(pools[name]), "required": sum(QUOTAS[name.split("__")[1]])}
                for name in BUCKETS if len(pools[name]) < sum(QUOTAS[name.split("__")[1]])}
    require(not deficits, "InsufficientBucketCapacityError: " + json.dumps(deficits, sort_keys=True))
    slots = {}
    for name in BUCKETS:
        nt, nd = QUOTAS[name.split("__")[1]]
        def digest(seed, r):
            return sha(f"{seed}:{name}:{r['item_id']}".encode("utf-8"))
        ordered = sorted(pools[name], key=lambda r: (0 if prefer and r["is_retained_v1"] else 1, digest(test_seed, r), *primary_key(r)))
        for index, r in enumerate(ordered[:nt], 1):
            r["status_code"] = "SELECTED_TEST"
            slots[r["item_id"]] = index
        remaining = sorted(ordered[nt:], key=lambda r: (digest(dev_seed, r), *primary_key(r)))
        for index, r in enumerate(remaining[:nd], 1):
            r["status_code"] = "SELECTED_DEV"
            slots[r["item_id"]] = index
        for index, r in enumerate(remaining[nd:], 1):
            r["reserve_rank"] = index
    def payload(r):
        s = lookup[r["item_id"]]
        return {**r, "question": s["question"], "final_answer": s["final_answer"][0],
                "answer_type": s["answer_type"], "solution": list(s["solution"]), "unit": s["unit"], "error": s["error"],
                "source_is_multiple_answer": s["is_multiple_answer"], "effective_is_multiple_answer": effective[r["item_id"]],
                "slot_index": slots.get(r["item_id"]),
                "needs_solution_asset_review": any(bool(re.search(IMAGE_PAT + "|" + VISUAL_WORDS, s_, flags=re.IGNORECASE)) for s_ in s["solution"])}
    selections = {}
    for status in ("SELECTED_TEST", "SELECTED_DEV", "ELIGIBLE_RESERVE"):
        rows = [r for r in records if r["status_code"] == status]
        rows.sort(key=lambda r: (bucket(r), r["reserve_rank"] if status == "ELIGIBLE_RESERVE" else slots[r["item_id"]]))
        selections[status] = [payload(r) for r in rows]
    output = {}
    buf = io.StringIO(newline="")
    writer = csv.DictWriter(buf, fieldnames=FIELDS, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    writer.writeheader()
    writer.writerows({k: csv_value(r[k]) for k in FIELDS} for r in records)
    output["selection_eligibility_ledger.csv"] = buf.getvalue().encode("utf-8")
    files = {"SELECTED_TEST": "provisional_test_100.jsonl", "SELECTED_DEV": "provisional_dev_20.jsonl", "ELIGIBLE_RESERVE": "eligible_reserve_pool.jsonl"}
    for status, filename in files.items():
        output[filename] = b"".join(canonical_json(r) for r in selections[status])
    by_reason = {why: sum(r["exclusion_reason"] == why for r in records) for why in REASONS}
    stages, entered = [], len(records)
    for stage in ("STAGE_1", "STAGE_2", "STAGE_3", "STAGE_4"):
        excluded = sum(r["exclusion_stage"] == stage for r in records)
        stages.append({"stage": stage, "entered": entered, "excluded": excluded, "passed": entered - excluded})
        entered -= excluded
    counts = {status: sum(r["status_code"] == status for r in records) for status in ("SELECTED_TEST", "SELECTED_DEV", "ELIGIBLE_RESERVE", "EXCLUDED")}
    buckets = {}
    for name in BUCKETS:
        nt, nd = QUOTAS[name.split("__")[1]]
        buckets[name] = {"total_eligible": len(pools[name]), "selected_test": nt, "selected_dev": nd, "reserve_count": len(pools[name]) - nt - nd}
    sources_meta = []
    for src, (n, digest_) in SOURCES.items():
        filename = f"OE_TO_maths_zh_{src}"
        sources_meta.append({"source_dataset": filename, "rows": n, "sha256": digest_,
                             "repository_path": f"OlympiadBench/{filename}/{filename}.parquet"})
    lengths = {"selection_eligibility_ledger.csv": len(records), **{files[k]: len(v) for k, v in selections.items()}}
    manifest = {
        "schema_version": "selection_manifest_v2.3", "rule_version": RULE_VERSION,
        "rules_sha256": sha(Path(__file__).read_bytes()), "selection_status": "PROVISIONAL_NOT_FROZEN",
        "dataset_repository": "Hothan/OlympiadBench", "dataset_revision": REVISION, "sources": sources_meta,
        "audit": {"schema_version": audit["schema_version"], "sha256": AUDIT_SHA256, "flag_corrections_applied": applied},
        "retained_input": retained_metadata,
        "parameters": {"test_seed": test_seed, "dev_seed": dev_seed, "prefer_retained": prefer, "test_total": 100, "dev_total": 20},
        "funnel": {"stages": stages, "by_reason": by_reason}, "buckets": buckets, "status_counts": counts,
        "outputs": {name: {"sha256": sha(data), "bytes": len(data), "records": lengths[name]} for name, data in sorted(output.items())},
    }
    output["selection_manifest.json"] = canonical_json(manifest)
    output["selection_manifest.json.sha256"] = (sha(output["selection_manifest.json"]) + "\n").encode("ascii")
    return output
